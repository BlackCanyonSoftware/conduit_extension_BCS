// Regenerates src/core/cookies/public-suffix-data.ts from the Public Suffix List.
//
//   node scripts/update-public-suffixes.mjs            fetch the current list
//   node scripts/update-public-suffixes.mjs list.dat   use a copy you already have
//
// The list is published at https://publicsuffix.org/list/public_suffix_list.dat under the
// Mozilla Public License 2.0. Run this now and then and commit the result; nothing fetches it
// while the extension runs.
import { readFile, writeFile } from 'node:fs/promises';
import { domainToASCII } from 'node:url';

const SOURCE = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUT = new URL('../src/core/cookies/public-suffix-data.ts', import.meta.url);

async function readList(argument) {
  if (argument) return readFile(argument, 'utf8');
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`${SOURCE} answered ${String(response.status)}`);
  return response.text();
}

/** One rule in the form the matcher reads: lower case, ASCII (punycode), `*.` and `!` kept. */
function toRule(token) {
  const prefix = token.startsWith('!') ? '!' : token.startsWith('*.') ? '*.' : '';
  const name = domainToASCII(token.slice(prefix.length).toLowerCase());
  if (name === '') throw new Error(`cannot convert the rule ${token}`);
  return prefix + name;
}

const text = await readList(process.argv[2]);
const version = /^\/\/ VERSION: (.+)$/m.exec(text)?.[1] ?? 'unknown';
const commit = /^\/\/ COMMIT: (.+)$/m.exec(text)?.[1] ?? 'unknown';

const rules = new Set();
for (const line of text.split(/\r?\n/)) {
  const token = line.trim().split(/\s+/)[0];
  if (token === undefined || token === '' || token.startsWith('//')) continue;
  rules.add(toRule(token));
}
if (rules.size < 5000) throw new Error(`only ${String(rules.size)} rules: this is not the list`);

const body = [...rules].sort().join('\n');
await writeFile(
  OUT,
  `// Generated by scripts/update-public-suffixes.mjs. Do not edit by hand.
//
// The Public Suffix List, version ${version}, commit ${commit}.
// Source: ${SOURCE}
// Licence: Mozilla Public License 2.0, https://mozilla.org/MPL/2.0/ . This file is the list's
// data (rules in lower-case ASCII, one per line) and stays under that licence.

export const PUBLIC_SUFFIX_LIST_VERSION = '${version}';

export const PUBLIC_SUFFIX_RULES = \`
${body}
\`;
`,
);
console.log(`wrote ${String(rules.size)} rules (list version ${version})`);
